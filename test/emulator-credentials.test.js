import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { readEmulatorCredentialEnvironment } from "../dist/emulator-credentials.js";

async function withCredentialsFile(contents, callback) {
  const directory = await mkdtemp(path.join(os.tmpdir(), "awesome-emulator-credentials-"));
  const filename = path.join(directory, "credentials");
  await writeFile(filename, contents, "utf8");
  try {
    await callback(filename);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

test("reads default profile credentials with comments, BOM, whitespace, and CRLF", async () => {
  await withCredentialsFile("\uFEFF# emulator credentials\r\n; generated by the emulator\r\n[profile other]\r\naws_access_key_id = OTHER\r\n[DeFaUlT]\r\nnot-an-entry\r\naws_access_key_id = emulator-key  \r\naws_secret_access_key= emulator-secret\r\naws_session_token = emulator-token\r\nunknown = ignored\r\n", async (filename) => {
    assert.deepEqual(await readEmulatorCredentialEnvironment(filename), {
      AWS_ACCESS_KEY_ID: "emulator-key",
      AWS_SECRET_ACCESS_KEY: "emulator-secret",
      AWS_SESSION_TOKEN: "emulator-token",
    });
  });
});

test("omits an empty session token and ignores credentials outside the default profile", async () => {
  await withCredentialsFile("[other]\naws_access_key_id = NOT_DEFAULT\n[default]\naws_access_key_id = key\naws_secret_access_key = secret\naws_session_token =   \n", async (filename) => {
    assert.deepEqual(await readEmulatorCredentialEnvironment(filename), {
      AWS_ACCESS_KEY_ID: "key",
      AWS_SECRET_ACCESS_KEY: "secret",
    });
  });
});

test("rejects incomplete default credentials", async () => {
  for (const contents of [
    "[default]\naws_access_key_id = key\n",
    "[default]\naws_secret_access_key = secret\n",
    "[default]\naws_access_key_id = \naws_secret_access_key = secret\n",
    "[named]\naws_access_key_id = key\naws_secret_access_key = secret\n",
  ]) {
    await withCredentialsFile(contents, async (filename) => {
      await assert.rejects(readEmulatorCredentialEnvironment(filename), /does not contain a usable \[default\]/);
    });
  }

});

test("preserves file-system errors when the credential file cannot be read", async () => {
  await assert.rejects(readEmulatorCredentialEnvironment(path.join(os.tmpdir(), `missing-${Date.now()}`)), { code: "ENOENT" });
});
